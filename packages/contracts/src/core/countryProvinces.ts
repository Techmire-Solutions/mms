/** Returns standard state/province options for a given country name (empty array if unknown). */
export function getProvincesForCountry(country?: string | null): string[] {
  if (!country) return [];
  const key = country.trim().toLowerCase();
  const list = COUNTRY_PROVINCES_MAP[key];
  return list ? [...list] : [];
}
