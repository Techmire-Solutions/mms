#!/usr/bin/env bash
# Mirror the canonical agent standards to DeepSeek Harness:
#   .agent/rules/*.md        → .dsh/rules/
#   .agent/skills/<name>/**  → .dsh/skills/<name>/**
#   .dsh/AGENTS.md           → generated index (rules + skills + load model)
# DSH discovers skills from <projectRoot>/.dsh/skills (rank 100) and loads the
# project AGENTS.md/CLAUDE.md chain for instructions; it has no glob-scoped rule
# loader, so rules are mirrored for on-demand reading.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

DRY_RUN=0
for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

export MMS_SYNC_DRY_RUN="$DRY_RUN"
# `node -` forces script mode: a bare `node <<` starts the REPL under Git Bash on Windows.
node - <<'SCRIPT'
const fs = require("fs");
const path = require("path");

const DRY = process.env.MMS_SYNC_DRY_RUN === "1";
const rulesSrc = ".agent/rules";
const skillsSrc = ".agent/skills";
const dshRules = ".dsh/rules";
const dshSkills = ".dsh/skills";
const dshAgents = ".dsh/AGENTS.md";

const read = (p) => fs.readFileSync(p, "utf8");
const stripFrontmatter = (text) => {
  const m = text.replace(/\r\n/g, "\n").match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  return m ? { front: m[1], body: m[2] } : { front: "", body: text };
};
const field = (front, key) => {
  const m = front.match(new RegExp(`^${key}:\\s*(.+)$`, "m"));
  return m ? m[1].trim().replace(/^["']|["']$/g, "") : "";
};
const oneLine = (text, max = 140) => {
  const flat = text.replace(/\s+/g, " ").trim();
  return flat.length > max ? `${flat.slice(0, max - 1).trimEnd()}…` : flat;
};
const cell = (text) => text.replace(/\|/g, "\\|");

// ── Rules: byte-identical copy of .agent/rules ────────────────────────────────
const ruleFiles = fs.readdirSync(rulesSrc).filter((f) => f.endsWith(".md")).sort();
if (DRY) {
  console.log(`would mirror ${ruleFiles.length} rule files → ${dshRules}/`);
} else {
  fs.rmSync(dshRules, { recursive: true, force: true });
  fs.mkdirSync(dshRules, { recursive: true });
  for (const file of ruleFiles) {
    fs.copyFileSync(path.join(rulesSrc, file), path.join(dshRules, file));
  }
}

// ── Skills: clean per-skill copy (README at the skills root is NOT copied —
// a flat .md at .dsh/skills would be parsed as a broken skill) ───────────────
const skillDirs = fs
  .readdirSync(skillsSrc, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();
if (DRY) {
  console.log(`would mirror ${skillDirs.length} skill bundles → ${dshSkills}/`);
} else {
  fs.mkdirSync(dshSkills, { recursive: true });
  for (const entry of fs.readdirSync(dshSkills, { withFileTypes: true })) {
    if (!entry.isDirectory() || !skillDirs.includes(entry.name)) {
      fs.rmSync(path.join(dshSkills, entry.name), { recursive: true, force: true });
    }
  }
  for (const name of skillDirs) {
    const dest = path.join(dshSkills, name);
    fs.rmSync(dest, { recursive: true, force: true });
    fs.cpSync(path.join(skillsSrc, name), dest, { recursive: true });
  }
}

// ── Generated index ──────────────────────────────────────────────────────────
const cursorRules = fs
  .readdirSync(".cursor/rules")
  .filter((f) => f.endsWith(".mdc"))
  .sort();
const alwaysOn = new Set(
  cursorRules
    .filter((file) => /alwaysApply:\s*true/.test(stripFrontmatter(read(path.join(".cursor/rules", file))).front))
    .map((file) => file.replace(/\.mdc$/, "")),
);
const scoped = cursorRules.length - alwaysOn.size;

const ruleRows = cursorRules
  .map((file) => {
    const base = file.replace(/\.mdc$/, "");
    const { front } = stripFrontmatter(read(path.join(".cursor/rules", file)));
    return `| [${base}](rules/${base}.md) | ${cell(oneLine(field(front, "description"), 160))} | ${alwaysOn.has(base) ? "**yes**" : "—"} |`;
  })
  .join("\n");

const skillRows = skillDirs
  .map((name) => {
    const { front } = stripFrontmatter(read(path.join(skillsSrc, name, "SKILL.md")));
    return `| [${name}](skills/${name}/SKILL.md) | ${cell(oneLine(field(front, "description"), 150))} |`;
  })
  .join("\n");

const workflows = fs
  .readdirSync(".agent/workflows")
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => `[\`${f.replace(/\.md$/, "")}\`](../.agent/workflows/${f})`)
  .join(" · ");

const generated = `<!-- GENERATED by .agent/scripts/sync-dsh.sh — do not edit. Run: bash .agent/scripts/sync-all.sh -->
# MMS — DeepSeek Harness workspace

MMS standards corpus: **${cursorRules.length} rules** (${alwaysOn.size} always-on + ${scoped} scoped) · ${skillDirs.length} skills.

DeepSeek Harness loads project instructions from the repo-root \`AGENTS.md\` / \`CLAUDE.md\` chain and discovers skills from \`.dsh/skills\` (project root, rank 100 — \`dsh-base\` mounts \`@deepseek-ai/dsh-skill-filesystem\`). Rules have no DSH-native loader, so they are mirrored here for on-demand reading:

- \`.dsh/rules/<name>.md\` — full rule body, byte-identical to \`.agent/rules\`.
- \`.dsh/skills/<name>/SKILL.md\` — full skill bundle (\`references/\`, \`scripts/\`, \`examples/\`, \`data/\` included).
- Canonical sources: \`.cursor/rules/*.mdc\` (rules) and \`.agent/skills/*/SKILL.md\` (skills). Edit those, then run \`bash .agent/scripts/sync-all.sh\`.

## Rules

| Rule | Description | Always-on |
|---|---|---|
${ruleRows}

## Skills

| Skill | Description |
|---|---|
${skillRows}

## Workflows

${workflows}

## Verify

\`\`\`bash
node scripts/verify-rules-integrity.mjs   # mirror parity + citations
node scripts/check-docs.mjs               # docs index and links
bash .agent/scripts/sync-all.sh           # regenerate every mirror
\`\`\`
`;

if (DRY) {
  console.log(`would write ${dshAgents} (${cursorRules.length} rules, ${skillDirs.length} skills)`);
} else {
  fs.writeFileSync(dshAgents, generated, "utf8");
}
SCRIPT

if [[ "$DRY_RUN" == "1" ]]; then
  echo "Done (dry-run). DeepSeek Harness mirror: .dsh/rules + .dsh/skills + .dsh/AGENTS.md"
else
  echo "Done. DeepSeek Harness mirror: .dsh/rules + .dsh/skills + .dsh/AGENTS.md"
fi
